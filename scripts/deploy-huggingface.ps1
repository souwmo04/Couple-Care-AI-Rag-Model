<#
.SYNOPSIS
  Publish the current commit to a Hugging Face Space (Docker SDK).
.DESCRIPTION
  Copies the committed project (git archive of HEAD — uncommitted changes and .env are never included) into
  .cache\hf-deploy inside this project, adds the Space configuration README, and pushes it to the Space.
  Git asks for your Hugging Face username and an access token with write permission the first time.
.EXAMPLE
  scripts\deploy-huggingface.ps1 -Space yourname/couplecare-ai
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidatePattern('^[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*$')]
    [string]$Space
)
$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

$dirty = git status --porcelain
if ($dirty) { Write-Warning 'You have uncommitted changes; only the last commit is published.' }

$stage = Join-Path $Root '.cache\hf-deploy'
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
$url = "https://huggingface.co/spaces/$Space"

Write-Host "Cloning $url ..." -ForegroundColor Cyan
git clone --quiet $url $stage
if ($LASTEXITCODE) { throw "Could not clone $url. Create the Space first (SDK: Docker) and check the name." }

# Replace the Space contents with the committed project (keep the Space's .git and .gitattributes).
Get-ChildItem -Force $stage | Where-Object { $_.Name -notin @('.git', '.gitattributes') } | Remove-Item -Recurse -Force
$archive = Join-Path $stage 'project.tar'
git archive --format=tar -o $archive HEAD
tar -xf $archive -C $stage
Remove-Item $archive
# Not needed in the Space (and the Space README replaces the GitHub one).
foreach ($p in @('.github', 'research', 'docs\screenshots')) {
    $full = Join-Path $stage $p
    if (Test-Path $full) { Remove-Item -Recurse -Force $full }
}

$readme = @"
---
title: CoupleCare AI
emoji: 💞
colorFrom: red
colorTo: pink
sdk: docker
app_port: 7860
pinned: false
license: mit
short_description: Relationship support in English, Bangla and Banglish
---

# CoupleCare AI — demo

A relationship-support assistant in English, বাংলা and Banglish. This demo runs in cloud mode: replies are
generated by Groq, and voice input uses Groq Whisper. It is an educational tool, not therapy or a crisis
service — if you are in danger, contact your local emergency number.

Source code: https://github.com/souwmo04/Couple-Care-AI-Rag-Model
"@
[System.IO.File]::WriteAllText((Join-Path $stage 'README.md'), $readme, (New-Object System.Text.UTF8Encoding $false))

Push-Location $stage
try {
    git add -A
    $commit = (git -C $Root rev-parse --short HEAD).Trim()
    git commit --quiet -m "Deploy CoupleCare AI ($commit)"
    if ($LASTEXITCODE) { Write-Host 'Nothing changed since the last deploy.'; return }
    Write-Host 'Pushing to Hugging Face (enter your username and access token if asked) ...' -ForegroundColor Cyan
    git push --quiet origin HEAD:main
    if ($LASTEXITCODE) { throw 'Push failed. Use an access token with write permission as the password.' }
    Write-Host "Deployed. Hugging Face is now building the app: $url" -ForegroundColor Green
    Write-Host 'The first build takes about 10-15 minutes. Watch progress in the Space''s Logs tab.'
}
finally {
    Pop-Location
}
